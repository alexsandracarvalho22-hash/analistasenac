def soma_dois_numeros (numero1,numero2):

    '''

     retorna o somatório de dois números
    quiasquer.
'''

    soma = numero1 + numero2
    return soma


def subtracao_dois_numeros (numero1,numero2):

    '''

     retorna o subtracao de dois números
    quiasquer.
    '''

    subtracao = numero1 - numero2
    return subtracao





def multiplicacao_dois_numeros (numero1,numero2):

    '''

     retorna a multiplicacao de dois números
    quiasquer.
'''

    multiplicacao = numero1 * numero2
    return multiplicacao




def divisao_dois_numeros (numero1,numero2):

    '''

     retorna a divisao de dois números
    quiasquer.
'''

    divisao = numero1 / numero2
    return divisao


